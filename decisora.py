# CELL 6 — Process the 12 official monthly portfolio disclosures

import os

portfolio_files = sorted(
    DATA_DIR.glob("Monthly HDFC Large Cap Fund - *.xlsx"),
    key=lambda p: pd.to_datetime(
        p.stem.replace("Monthly HDFC Large Cap Fund - ", ""),
        format="%d %B %Y"
    )
)

portfolio_results = []
sector_results = []

for file in portfolio_files:

    data = pd.read_excel(
        file,
        sheet_name="HDFCT2",
        header=None
    )

    holdings = data.iloc[8:, [1, 3, 4, 5, 6, 7]].copy()

    holdings.columns = [
        "ISIN",
        "Instrument",
        "Industry",
        "Quantity",
        "Market_Value_Lacs",
        "Percent_to_NAV"
    ]

    holdings = holdings.dropna(subset=["Instrument"])

    holdings["Percent_to_NAV"] = pd.to_numeric(
        holdings["Percent_to_NAV"],
        errors="coerce"
    )

    holdings = holdings.dropna(subset=["Percent_to_NAV"])

    equity = holdings[
        holdings["ISIN"].astype(str).str.startswith("INE")
    ].copy()

    if equity.empty:
        continue

    top10 = (
        equity
        .sort_values("Percent_to_NAV", ascending=False)
        .head(10)
    )

    sector = (
        equity
        .groupby("Industry")["Percent_to_NAV"]
        .sum()
        .sort_values(ascending=False)
    )

    month = file.stem.replace(
        "Monthly HDFC Large Cap Fund - ", ""
    )

    portfolio_results.append({
        "Month": month,
        "Security_Count": len(equity),
        "Top_10_Concentration_%": top10["Percent_to_NAV"].sum(),
        "Top_Holding": top10.iloc[0]["Instrument"],
        "Top_Holding_Exposure": top10.iloc[0]["Percent_to_NAV"],
        "Largest_Sector": sector.index[0],
        "Largest_Sector_Exposure": sector.iloc[0],
    })

    sector_month = (
        equity
        .groupby("Industry")["Percent_to_NAV"]
        .sum()
        .reset_index()
    )
    sector_month["Month"] = month
    sector_results.append(sector_month)

portfolio_monthly = pd.DataFrame(portfolio_results)
portfolio_monthly["Month_Date"] = pd.to_datetime(
    portfolio_monthly["Month"],
    format="%d %B %Y"
)
portfolio_monthly = portfolio_monthly.sort_values(
    "Month_Date"
).reset_index(drop=True)

portfolio_monthly.to_csv(
    DATA_DIR / "HDFC_Large_Cap_2025_Portfolio_Monthly.csv",
    index=False
)

sector_df = pd.concat(sector_results, ignore_index=True)
sector_df["Month_Date"] = pd.to_datetime(
    sector_df["Month"],
    format="%d %B %Y"
)
sector_df.to_csv(
    DATA_DIR / "HDFC_Large_Cap_2025_Sector_Monthly.csv",
    index=False
)

print(f"✓ Portfolio files processed: {len(portfolio_files)}")
