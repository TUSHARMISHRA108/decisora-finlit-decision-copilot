# CELL 5 — Calculate real market context and save consolidated datasets

comparison = pd.merge(
    hdfc_2025[["Date", "Net Asset Value"]],
    nifty[["Date", "Total Returns Index"]],
    on="Date",
    how="inner"
).sort_values("Date").reset_index(drop=True)

comparison["HDFC_Daily_Return_%"] = (
    comparison["Net Asset Value"].pct_change() * 100
)

comparison["NIFTY_Daily_Return_%"] = (
    comparison["Total Returns Index"].pct_change() * 100
)

comparison["HDFC_Peak"] = (
    comparison["Net Asset Value"].cummax()
)

comparison["HDFC_Drawdown_%"] = (
    (comparison["Net Asset Value"] - comparison["HDFC_Peak"])
    / comparison["HDFC_Peak"]
) * 100

fund_return = (
    comparison["Net Asset Value"].iloc[-1]
    / comparison["Net Asset Value"].iloc[0] - 1
) * 100

benchmark_return = (
    comparison["Total Returns Index"].iloc[-1]
    / comparison["Total Returns Index"].iloc[0] - 1
) * 100

return_difference = fund_return - benchmark_return

max_dd_row = comparison.loc[
    comparison["HDFC_Drawdown_%"].idxmin()
]

drawdown_date = max_dd_row["Date"]
peak_nav = max_dd_row["HDFC_Peak"]

future = comparison[comparison["Date"] > drawdown_date]
recovery_rows = future[future["Net Asset Value"] >= peak_nav]

if not recovery_rows.empty:
    recovery_date = recovery_rows.iloc[0]["Date"]
    recovery_days = (recovery_date - drawdown_date).days
else:
    recovery_date = None
    recovery_days = None

hdfc_volatility = comparison["HDFC_Daily_Return_%"].std()
nifty_volatility = comparison["NIFTY_Daily_Return_%"].std()

returns = comparison[
    ["HDFC_Daily_Return_%", "NIFTY_Daily_Return_%"]
].dropna()

historical_beta = (
    returns["HDFC_Daily_Return_%"].cov(
        returns["NIFTY_Daily_Return_%"]
    )
    / returns["NIFTY_Daily_Return_%"].var()
)

master_daily = comparison.copy()
